export function translateDOM(root = document.body) {
  const lang = localStorage.getItem('gica_lang') || 'fr';
  if (lang === 'fr') {
    document.documentElement.setAttribute('lang', 'fr');
    document.documentElement.removeAttribute('dir');
    return;
  }

  document.documentElement.setAttribute('lang', 'ar');
  document.documentElement.setAttribute('dir', 'rtl');

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while (node = walker.nextNode()) {
    const trimmed = node.nodeValue.trim();
    if (trimmed) {
      // 1. Exact match
      if (dict[trimmed]) {
        node.nodeValue = node.nodeValue.replace(trimmed, dict[trimmed]);
      } else {
        // 2. Partial replaces
        let val = node.nodeValue;
        let changed = false;
        partialDict.forEach(p => {
          if (val.includes(p.fr)) {
            val = val.replaceAll(p.fr, p.ar);
            changed = true;
          }
        });
        if (changed) {
          node.nodeValue = val;
        }
      }
    }
  }

  // Translate placeholders
  root.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
    const ph = el.getAttribute('placeholder');
    if (ph && dict[ph]) {
      el.setAttribute('placeholder', dict[ph]);
    }
  });
}
